const { GoogleGenAI } = require('@google/genai');

/**
 * Supported Gemini Flash model configuration.
 * Default is 'gemini-3.8-flash'. Alternative supported Flash models include:
 * 'gemini-2.0-flash', 'gemini-1.5-flash'.
 */
const GEMINI_MODEL = process.env.GEMINI_MODEL || 'gemini-3.8-flash';

/**
 * System instruction defining the personality and behavior of universe.ai.
 */
const SYSTEM_INSTRUCTION = `You are universe.ai, an intelligent, helpful, friendly, and knowledgeable AI assistant inspired by the elegance, boundless curiosity, and depth of the cosmos.
- Explain complex subjects clearly and intuitively, adapting seamlessly to the user's background.
- Provide practical, well-explained code with commentary when coding assistance is requested.
- Structure your responses logically using clean markdown formatting (paragraphs, bullet points, headers, inline code, and syntax-highlighted code blocks).
- Be polite, constructive, concise when appropriate, and deeply engaging.`;

/**
 * Maximum character count per message to prevent oversized payloads.
 */
const MAX_MESSAGE_LENGTH = 4000;

/**
 * Maximum conversation history items to include in model context.
 */
const MAX_HISTORY_ITEMS = 20;

/**
 * Validates and transforms conversation history into the format required by the Google GenAI SDK.
 *
 * @param {Array<{role: string, content: string}>} history
 * @returns {Array<{role: 'user'|'model', parts: Array<{text: string}>}>}
 */
function sanitizeAndFormatHistory(history) {
  if (!Array.isArray(history)) {
    return [];
  }

  // Keep only the most recent items up to MAX_HISTORY_ITEMS
  const recentHistory = history.slice(-MAX_HISTORY_ITEMS);
  const formatted = [];

  for (const item of recentHistory) {
    if (!item || typeof item !== 'object') continue;

    const role = item.role;
    const content = typeof item.content === 'string' ? item.content.trim() : '';

    if (!content || (role !== 'user' && role !== 'assistant')) {
      continue;
    }

    const truncatedContent = content.slice(0, MAX_MESSAGE_LENGTH);
    const geminiRole = role === 'assistant' ? 'model' : 'user';

    // Avoid duplicate consecutive identical roles if possible, or append turn
    if (formatted.length > 0 && formatted[formatted.length - 1].role === geminiRole) {
      formatted[formatted.length - 1].parts[0].text += `\n\n${truncatedContent}`;
    } else {
      formatted.push({
        role: geminiRole,
        parts: [{ text: truncatedContent }]
      });
    }
  }

  // Gemini multi-turn contents should begin with 'user'
  while (formatted.length > 0 && formatted[0].role !== 'user') {
    formatted.shift();
  }

  return formatted;
}

/**
 * Generates an AI chat response using Google GenAI SDK.
 *
 * @param {Object} params
 * @param {string} params.message - Current user prompt
 * @param {Array} [params.history=[]] - Previous conversational turns
 * @returns {Promise<string>} - Assistant response text
 */
async function generateChatResponse({ message, history = [] }) {
  const apiKey = process.env.GEMINI_API_KEY ? process.env.GEMINI_API_KEY.trim() : '';

  if (!apiKey || apiKey === 'your_api_key_here') {
    const error = new Error('Gemini API key is not configured. Please set a valid GEMINI_API_KEY in your .env file.');
    error.statusCode = 503;
    error.isOperational = true;
    throw error;
  }

  const cleanMessage = typeof message === 'string' ? message.trim() : '';
  if (!cleanMessage) {
    const error = new Error('Message cannot be empty.');
    error.statusCode = 400;
    error.isOperational = true;
    throw error;
  }

  if (cleanMessage.length > MAX_MESSAGE_LENGTH) {
    const error = new Error(`Message exceeds maximum limit of ${MAX_MESSAGE_LENGTH} characters.`);
    error.statusCode = 400;
    error.isOperational = true;
    throw error;
  }

  // Format conversation history and append latest user message
  const formattedContents = sanitizeAndFormatHistory(history);
  formattedContents.push({
    role: 'user',
    parts: [{ text: cleanMessage }]
  });

  try {
    const ai = new GoogleGenAI({ apiKey });

    const response = await ai.models.generateContent({
      model: GEMINI_MODEL,
      contents: formattedContents,
      config: {
        systemInstruction: SYSTEM_INSTRUCTION,
        temperature: 0.7,
      }
    });

    const reply = response.text || (
      response.candidates?.[0]?.content?.parts?.map((p) => p.text).join('') ?? ''
    );

    if (!reply) {
      throw new Error('No response was generated by Gemini.');
    }

    return reply;
  } catch (err) {
    // If it's already an operational error we constructed, rethrow
    if (err.isOperational) {
      throw err;
    }

    // Map common Gemini API status codes / messages to friendly user-facing errors
    const status = err.status || err.statusCode || 500;
    const msg = String(err.message || '');
    let friendlyMessage = 'Unable to generate response from universe.ai. Please try again.';
    let httpStatus = 500;

    if (status === 400 || msg.includes('API key not valid') || msg.includes('INVALID_ARGUMENT')) {
      friendlyMessage = 'The configured Gemini API key is invalid or unrecognized. Please check your .env configuration.';
      httpStatus = 401;
    } else if (status === 403 || msg.includes('PERMISSION_DENIED')) {
      friendlyMessage = 'Access denied by Gemini API. Please ensure your API key has appropriate permissions.';
      httpStatus = 403;
    } else if (status === 429 || msg.includes('RESOURCE_EXHAUSTED')) {
      friendlyMessage = 'Gemini API rate limit or quota exceeded. Please wait a moment before trying again.';
      httpStatus = 429;
    } else if (status === 503 || msg.includes('UNAVAILABLE')) {
      friendlyMessage = 'Gemini service is temporarily unavailable. Please try again in a few moments.';
      httpStatus = 503;
    } else if (msg.includes('ENOTFOUND') || msg.includes('ETIMEDOUT') || msg.includes('fetch failed')) {
      friendlyMessage = 'Network connection failed while connecting to Gemini. Please check your internet connectivity.';
      httpStatus = 502;
    }

    const publicError = new Error(friendlyMessage);
    publicError.statusCode = httpStatus;
    publicError.isOperational = true;

    // Log internal error safely on the server without leaking API keys
    console.error(`[universe.ai Error] Status: ${status} | Detail: ${msg.replace(/key=[^&]+/i, 'key=REDACTED')}`);

    throw publicError;
  }
}

module.exports = {
  GEMINI_MODEL,
  MAX_MESSAGE_LENGTH,
  MAX_HISTORY_ITEMS,
  generateChatResponse
};
